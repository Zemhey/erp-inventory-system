-- ============================================================================
-- V7 · M2 补口：给 FINANCE 补 `mdm:read`（解 .plan/M2-计划书.md §6 坑 16）
-- 范围：**只追加一条角色→权限种子，不动任何表结构、不动 V1~V6 的任何已合并文件**
--
-- 为什么需要它（S5b 实测）：结算页与报表页要把 id 显示成名字，需要
--   `GET /warehouses`（仓库名 + 月结/报表的仓库下拉候选），报表页还要
--   `/skus` + `/products`。V5 给 FINANCE 的只有 `rma:*` / `set:*` / `rpt:*`
--   三组码 → 每个字典请求都是 403。页面若照常拉字典，进页面瞬间挂一串红条。
--   同族问题（工作台在 FINANCE 下的 5 个 403）见下面"本次不修"。
--
-- 三个候选方案的定夺（计划书 §6 坑 16 交给 S7 抉择）：
--   ①【本次采用】补 `('FINANCE','mdm:read')`：一行种子，与其它只读角色一致
--     —— V3 早就给 PURCHASER / SALESPERSON / VIEWER 发了同一个码，
--     FINANCE 是唯一没有它的读角色，更像 V5 漏种而不是刻意的职责设计。
--   ② 把名称内联进结算/报表响应：最干净（前端不再需要字典），但要改 5 个响应
--     schema（日清 items / 月结 / 对账 / 三张报表），而 M2 已把报表定为
--     "只读聚合、不加展示字段"（§3.5），成本高且会把展示逻辑塞进聚合 SQL。
--   ③ 工作台按权限分块聚合：属 M3 页面，与本泳道无关。
--
-- 代价与可接受性：财务因此能看**全部**主数据（供应商/客户/商品/SKU/仓库）。
--   可接受的理由是 `mdm:read` 只覆盖读：`mdm:create/update/disable` 一个都没有
--   （AppUser#hasPermission 按 "模块:动作" 精确匹配，通配只认角色实际持有的
--   `模块:*`，而 FINANCE 没有任何 `模块:*`）。主数据本身也不是保密数据 ——
--   同系统里的采购员与销售员早就能看全。职责分离要拦的是"财务能改主数据/开单"，
--   这一条仍然成立：FINANCE 建进货单依旧 403（TC-API-017 守着你）。
--
-- 前端不改：`session.hasPermission('mdm:read')` 的降级分支（显示「仓库#编号」、
--   仓库筛选不可用）作为**防御**保留 —— 权限数据由部署环境决定，
--   页面不该假设某个角色一定持有某个码。
--
-- 本次登记但**不修**（M3 遗留，写进本泳道报告）：FINANCE 登录后工作台仍会对
--   `/inventory`、`/purchase-orders`、`/sales-orders`、`/inventory/consistency-check`
--   报 403（`inv:*` / `pur:read` / `sal:read` 都不在 FINANCE 的种子里）。
--   修它要么给财务扩权（越权读单据），要么让工作台按权限分块（改 M3 页面），
--   两条都超出"解坑 16 的字典 403"这一范围。
--
-- 沿用 M1 规则：**迁移里绝不创建账号**，只种角色→权限。
--
-- 刻意不加 `ON CONFLICT DO NOTHING`：这一行如果与既有种子重复，
-- 说明有人又在别处给 FINANCE 发过同一个码 —— 让迁移报错比静默跳过更容易被发现。
-- ============================================================================

INSERT INTO app_role_permissions (role_id, permission)
SELECT r.id, 'mdm:read' FROM app_roles r WHERE r.code = 'FINANCE';
